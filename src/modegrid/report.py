"""Collect every number paper/results.md asks for into one file, results/report.md.

paper/results.md names, before any scoring, the file and column behind each number in the
Results section. This module reads those files and lays the numbers out in the section's
order, so writing the section is copying, not choosing. It applies only the rules the
pre-registration states (the alpha bars, the blinding rule, the H3 outcomes) and decides
nothing new. A file that is not there yet is named with the command that makes it.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

from . import DIMS
from .analyze import ALPHA_BAR, HYPOTHESES, hypothesis_status

FIRM_BAR = 0.800  # pre-registration section 4: alpha between 0.667 and 0.800 is "tentative"
BLINDING_P = 0.05  # pre-registration section 4: a rater beats chance on mode below this
RATERS = ("human", "llm-a", "llm-b")
MEASURES = (*DIMS, "total")
SUPPORTED_VERDICT = {"mode > model", "model > mode"}


def _read(path: Path) -> list[dict[str, str]] | None:
    if not path.exists():
        return None
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _num(v: str | float | None) -> float:
    try:
        return float(v)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return math.nan


def _f(v: str | float | None, nd: int = 3) -> str:
    x = _num(v)
    return "n/a" if math.isnan(x) else f"{x:.{nd}f}"


def _ci(lo: str | float | None, hi: str | float | None, nd: int = 3) -> str:
    return f"[{_f(lo, nd)}, {_f(hi, nd)}]"


def _effect(row: dict[str, str], nd: int = 3) -> str:
    """Reasoning minus fast with its 95% CI."""
    return f"{_f(row['mode_effect'], nd)} {_ci(row['mode_effect_ci_low'], row['mode_effect_ci_high'], nd)}"


def _missing(what: str, command: str) -> list[str]:
    return [f"Not run yet: {what}. Run `{command}`.", ""]


def _by(rows: list[dict[str, str]] | None, key: str) -> dict[str, dict[str, str]]:
    return {r[key]: r for r in rows or []}


def _status(row: dict[str, str], hid: str, alphas: dict[str, float] | None, blinding_failed: bool) -> str:
    """The analysis status, plus the two labels the pre-registration adds on top of it."""
    h = HYPOTHESES[hid]
    parsed: dict[str, object] = {k: v if k in ("dimension", "name", "verdict") else _num(v) for k, v in row.items()}
    status = hypothesis_status(parsed, h, alphas)
    if status.startswith("yes"):
        alpha = (alphas or {}).get(h.dim, math.nan)
        if math.isfinite(alpha) and alpha < FIRM_BAR:
            status += f", tentative (alpha {alpha:.2f} below {FIRM_BAR:.3f})"
        if hid == "H4" and blinding_failed:
            status += ", tentative, mode blinding failed"
    return status


def _ci_p_note(row: dict[str, str]) -> str:
    """The reasoning-minus-fast CI and the mode permutation p-value test the same effect."""
    lo, hi, p = _num(row.get("mode_effect_ci_low")), _num(row.get("mode_effect_ci_high")), _num(row.get("p_mode"))
    if any(math.isnan(x) for x in (lo, hi, p)):
        return "not computable"
    excludes = lo > 0 or hi < 0
    if excludes and p >= BLINDING_P:
        return "disagree: the CI excludes zero but p mode >= 0.05. Report both"
    if not excludes and p < BLINDING_P:
        return "disagree: p mode < 0.05 but the CI includes zero. Report both"
    return "agree"


def _blinding(rows: list[dict[str, str]] | None) -> tuple[list[str], bool]:
    """Raters who beat chance on mode, and whether all three did."""
    beat = [r["rater"] for r in rows or [] if r["guess"] == "guess_mode" and _num(r["p_value"]) < BLINDING_P]
    return beat, bool(rows) and set(RATERS) <= set(beat)


def build_report(results: str | Path = "results", scores: str | Path = "data/scores", planned: int = 60) -> str:
    res, sc = Path(results), Path(scores)
    table = _read(res / "variance_table.csv")
    agreement = _read(res / "agreement.csv")
    blinding = _read(res / "blinding_check.csv")
    by_dim = _by(table, "dimension")
    alphas = {r["dimension"]: _num(r["alpha"]) for r in agreement} if agreement else None
    beat, all_beat = _blinding(blinding)

    out = [
        "# Numbers for the Results section",
        "",
        "Written by `modegrid report` from the files in `results/`. The sections follow",
        "`paper/results.md`. Rules applied here are the pre-registered ones and nothing else.",
        "Copy the numbers across. Do not edit this file by hand: re-run the command.",
        "",
    ]

    # 4.1 Data and reliability
    out += ["## 4.1 Data and reliability", ""]
    adjudicated = _read(sc / "adjudicated.csv")
    if adjudicated is None:
        out += _missing("consensus scores", "modegrid unblind data/scores/adjudicated-blind.csv")
    else:
        out += [f"{len(adjudicated)} of {planned} planned answers have a consensus score.", ""]
    cells = _read(res / "cell_means.csv")
    if cells is None:
        out += _missing("cell means", "modegrid cells --figure figure1.pdf")
    else:
        zero = [f"{r['family']} {r['mode']}: {r['n_all_zero']}" for r in cells if int(r["n_all_zero"])]
        out += [
            "Answers scored 0 on all nine dimensions (possible refusals, check the raters' notes): "
            + (", ".join(zero) if zero else "0 in every cell")
            + ".",
            "",
        ]
    if agreement is None:
        out += _missing(
            "agreement",
            "modegrid agreement data/scores/human.csv data/scores/llm-a.csv data/scores/llm-b.csv "
            "--out results/agreement.csv",
        )
    else:
        out += ["Table 3. Krippendorff's alpha, three raters (ordinal per dimension, interval on the total).", ""]
        out += ["| Dim | alpha | status |", "|---|---|---|"]
        out += [f"| {r['dimension']} | {_f(r['alpha'])} | {r['status']} |" for r in agreement]
        below = [r["dimension"] for r in agreement if r["dimension"] != "total" and _num(r["alpha"]) < ALPHA_BAR]
        total = _num(_by(agreement, "dimension").get("total", {}).get("alpha"))
        out += [
            "",
            f"Dimensions below {ALPHA_BAR} (their tests are exploratory): {', '.join(below) or 'none'}.",
            "",
        ]
        if math.isnan(total):
            out += ["Total alpha: missing.", ""]
        else:
            gate = "at or above" if total >= ALPHA_BAR else "below"
            h4 = "H4 stays confirmatory" if total >= ALPHA_BAR else "H4 is exploratory"
            firm = (
                f"at or above {FIRM_BAR:.3f}, so a supported result is firm"
                if total >= FIRM_BAR
                else f"below {FIRM_BAR:.3f}, so a supported result is tentative"
            )
            out += [f"Total alpha {total:.3f}: {gate} {ALPHA_BAR}, so {h4}. It is {firm}.", ""]
    for other in ("llm-a", "llm-b"):
        pair = _read(res / f"agreement-human-{other}.csv")
        if pair is None:
            out += _missing(
                f"human vs {other} agreement",
                f"modegrid agreement data/scores/human.csv data/scores/{other}.csv "
                f"--out results/agreement-human-{other}.csv",
            )
            continue
        dims = [_num(r["exact_agreement_1v2"]) for r in pair if r["dimension"] in DIMS]
        dims = [d for d in dims if not math.isnan(d)]
        if dims:
            out += [
                f"Human vs {other}: exact agreement {sum(dims) / len(dims):.2f} on average over D1 to D9 "
                f"(range {min(dims):.2f} to {max(dims):.2f}).",
                "",
            ]

    # 4.2 Confirmatory test
    out += ["## 4.2 Confirmatory test (H4)", ""]
    t = by_dim.get("total")
    if t is None:
        out += _missing("the analysis", "modegrid analyze --agreement results/agreement.csv")
    else:
        inter = _num(t["omega2_interaction"])
        mains = max(_num(t["omega2_mode"]), _num(t["omega2_family"]))
        out += [
            f"- delta omega squared: {_f(t['delta_omega2'])}, 95% CI {_ci(t['ci_low'], t['ci_high'])}",
            f"- omega squared, mode: {_f(t['omega2_mode'])}. Family: {_f(t['omega2_family'])}",
            f"- reasoning minus fast: {_f(t['mode_effect'])} points of 18, 95% CI "
            f"{_ci(t['mode_effect_ci_low'], t['mode_effect_ci_high'])}",
            f"- permutation p: mode {_f(t['p_mode'])}, family {_f(t['p_family'])}. CI and p mode: {_ci_p_note(t)}",
            f"- omega squared, interaction: {_f(t['omega2_interaction'])}. Exceeds both main effects: "
            f"{'yes' if inter > mains else 'no'}",
            f"- verdict: {t['verdict']}",
            f"- H4 status: {_status(t, 'H4', alphas, all_beat)}",
            "",
        ]

    # 4.3 Secondary tests
    out += ["## 4.3 Secondary tests (H1 to H3) and the other dimensions", ""]
    if table is None:
        out += _missing("the analysis", "modegrid analyze --agreement results/agreement.csv")
    else:
        for hid in ("H1", "H2", "H3"):
            h = HYPOTHESES[hid]
            r = by_dim[h.dim]
            out += [
                f"{hid} ({h.dim}, predicted {h.predicted}): verdict {r['verdict']}. "
                f"delta {_f(r['delta_omega2'])} {_ci(r['ci_low'], r['ci_high'])}. "
                f"Reasoning minus fast {_effect(r)}. "
                f"CI and p mode: {_ci_p_note(r)}. Status: {_status(r, hid, alphas, all_beat)}.",
                "",
            ]
        d3 = by_dim["D3"]
        if d3["verdict"] == "model > mode":
            h3 = "model > mode, which supports H3"
        elif d3["verdict"] == "mode > model" and _num(d3["mode_effect_ci_high"]) < 0:
            h3 = "mode > model with reasoning lower, which supports the hallucination account"
        else:
            h3 = "neither pre-stated outcome"
        if alphas and alphas.get("D3", 1.0) < ALPHA_BAR:
            # Pre-registration section 4: a dimension below the bar cannot confirm or refute.
            h3 = h3.replace("which supports", "the direction of") + (
                f"; D3's alpha {alphas['D3']:.2f} is below {ALPHA_BAR}, so this can neither confirm nor refute it"
            )
        out += [f"H3 outcome: {h3}.", ""]
        rest = ("D2", "D4", "D5", "D6", "D7", "D8")
        out += ["Other dimensions (descriptive): " + ", ".join(f"{d} {by_dim[d]['verdict']}" for d in rest) + ".", ""]
        # Pre-registration section 5: interaction above both main effects, and CI/p
        # disagreements, are reported for every dimension, not only the hypotheses.
        over = [
            d
            for d in (*DIMS, "total")
            if _num(by_dim[d].get("omega2_interaction"))
            > max(_num(by_dim[d].get("omega2_family")), _num(by_dim[d].get("omega2_mode")))
        ]
        out += [
            "Interaction exceeds both main effects (average effect only): " + (", ".join(over) or "none") + ".",
            "",
        ]
        disagree = [d for d in rest if _ci_p_note(by_dim[d]).startswith("disagree")]
        out += ["CI and p mode disagree (other dimensions): " + (", ".join(disagree) or "none") + ".", ""]
        flat = [r["dimension"] for r in table if r["verdict"] in ("no variance", "uninformative (low variance)")]
        out += [f"No variance or uninformative: {', '.join(flat) or 'none'}.", ""]

    # 4.4 Per-family differences
    out += ["## 4.4 Where mode mattered: per-family differences", ""]
    effects = _read(res / "family_mode_effects.csv")
    if effects is None or t is None:
        out += _missing("per-family effects", "modegrid analyze --agreement results/agreement.csv")
    else:
        fam = [r for r in effects if r["dimension"] == "total"]
        out += ["| Family | fast | reasoning | reasoning - fast |", "|---|---|---|---|"]
        out += [
            f"| {r['family']} | {_f(r['fast_mean'], 2)} | {_f(r['reasoning_mean'], 2)} | "
            f"{_f(r['reasoning_minus_fast'], 2)} |"
            for r in fam
        ]
        avg = _num(t["mode_effect"])
        sign = (avg > 0) - (avg < 0)
        same = sum(1 for r in fam if ((d := _num(r["reasoning_minus_fast"])) > 0) - (d < 0) == sign and sign)
        out += ["", f"{same} of {len(fam)} families moved in the same direction as the average ({_f(avg, 2)}).", ""]

    # 4.5 Robustness
    out += ["## 4.5 Robustness", ""]
    if table is not None:
        out += [
            "| Dim | delta (raw) | delta (ranks) | same sign | delta (length-adjusted) "
            "| reasoning - fast (raw) | reasoning - fast (length-adjusted) | mode effect shrinks |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in table:
            raw, rk, ln = (_num(r[k]) for k in ("delta_omega2", "rank_delta_omega2", "length_adj_delta_omega2"))
            same_sign = "n/a" if math.isnan(rk) else ("yes" if (raw > 0) == (rk > 0) else "no")
            # Robustness check 2 is about the mode effect, not delta: delta mixes in the
            # family share, so it can move for reasons unrelated to length.
            me, me_ln = _num(r.get("mode_effect")), _num(r.get("length_adj_mode_effect"))
            shrinks = "n/a" if math.isnan(me_ln) else ("yes" if abs(me_ln) < abs(me) else "no")
            out.append(
                f"| {r['dimension']} | {_f(raw)} | {_f(rk)} | {same_sign} | {_f(ln)} | {_f(me)} | {_f(me_ln)} "
                f"| {shrinks} |"
            )
        out += ["", "Per rater (robustness check 3), verdict and reasoning minus fast with 95% CI:", ""]
        out += ["| Rater | H1 (D1) | H2 (D9) | H3 (D3) | H4 (total) |", "|---|---|---|---|---|"]
        for rater in RATERS:
            rows = _by(_read(res / rater / "variance_table.csv"), "dimension")
            if not rows:
                out.append(f"| {rater} | not run yet | | | |")
                continue
            cells_ = [f"{rows[h.dim]['verdict']}, {_effect(rows[h.dim], 2)}" for h in HYPOTHESES.values()]
            out.append(f"| {rater} | {' | '.join(cells_)} |")
        out += ["", "Fast-mode floor (robustness check 4):", ""]
        out += ["| Group | measure | delta (95% CI) | reasoning - fast (95% CI) | verdict |", "|---|---|---|---|---|"]
        floor: dict[str, dict[str, dict[str, str]]] = {}
        for group in ("fast-off", "fast-lowest"):
            rows = _by(_read(res / group / "variance_table.csv"), "dimension")
            floor[group] = rows
            if not rows:
                out.append(f"| {group} | not run yet | | | |")
                continue
            for m in ("total", "D1", "D9"):
                g = rows[m]
                out.append(
                    f"| {group} | {m} | {_f(g['delta_omega2'])} {_ci(g['ci_low'], g['ci_high'])} | "
                    f"{_effect(g, 2)} | {g['verdict']} |"
                )
        out.append("")
        if all(floor.values()):
            for hid in ("H1", "H2", "H4"):
                h = HYPOTHESES[hid]
                off = floor["fast-off"][h.dim]["verdict"] == h.predicted
                low = floor["fast-lowest"][h.dim]["verdict"] == h.predicted
                if off and not low:
                    out += [
                        f"{hid} holds in the true-off group only: the claim is for reasoning off vs on, "
                        "not minimised vs on.",
                        "",
                    ]

    # 4.6 Blinding
    out += ["## 4.6 Blinding", ""]
    if blinding is None:
        out += _missing(
            "the blinding check",
            "modegrid blinding-check data/scores/human.csv data/scores/llm-a.csv data/scores/llm-b.csv "
            "--out results/blinding_check.csv",
        )
    else:
        out += ["| Rater | guess | guessed | accuracy | chance | p |", "|---|---|---|---|---|---|"]
        for r in blinding:
            out.append(
                f"| {r['rater']} | {r['guess'].removeprefix('guess_')} | {int(_num(r['guessed']))} of "
                f"{int(_num(r['items']))} | {_f(r['accuracy'], 2)} | {_f(r['chance'], 2)} | {_f(r['p_value'])} |"
            )
        out.append("")
        if not beat:
            out += ["No rater beat chance on mode.", ""]
        else:
            out += [f"Beat chance on mode (p < {BLINDING_P}): {', '.join(beat)}. See the per-rater table in 4.5.", ""]
            if all_beat:
                out += ['All three beat chance: a supported H4 is "tentative, mode blinding failed".', ""]
            else:
                clean = [r for r in RATERS if r not in beat]
                agree = []
                for rater in clean:
                    rows = _by(_read(res / rater / "variance_table.csv"), "dimension")
                    if rows and t is not None:
                        agree.append(f"{rater} H4 verdict {rows['total']['verdict']} (consensus {t['verdict']})")
                out += [f"Raters who did not beat chance: {', '.join(agree) or 'per-rater runs missing'}.", ""]

    # 4.7 Rubric portability
    out += ["## 4.7 Rubric portability (exploratory)", ""]
    ranks = _read(res / "cell_rank_agreement.csv")
    if ranks is None:
        out += _missing(
            "rank agreement",
            "modegrid rank-agreement data/scores/human-unblinded.csv data/scores/llm-a-unblinded.csv "
            "data/scores/llm-b-unblinded.csv --out results/cell_rank_agreement.csv",
        )
    else:
        out += ["| Measure | Kendall's W | tau-b per pair |", "|---|---|---|"]
        for m in MEASURES:
            stats = [r for r in ranks if r["measure"] == m]
            kw = next((r["value"] for r in stats if r["statistic"] == "kendall_w"), "nan")
            taus = ", ".join(
                f"{r['comparison']} {_f(r['value'], 2)}" for r in stats if r["statistic"] == "kendall_tau_b"
            )
            out.append(f"| {m} | {_f(kw)} | {taus} |")
        out.append("")

    # 4.8 Own-vendor scores
    out += ["## 4.8 Own-vendor scores", ""]
    own = _read(res / "own_vendor.csv")
    if own is None:
        out += _missing(
            "own-vendor scores",
            "modegrid own-vendor data/scores/human-unblinded.csv data/scores/llm-a-unblinded.csv "
            "data/scores/llm-b-unblinded.csv --out results/own_vendor.csv",
        )
    else:
        out += [
            "| Rater | family | measure | own gap | baseline gap | self-preference (95% CI) | CI |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in own:
            lo, hi = _num(r["self_preference_ci_low"]), _num(r["self_preference_ci_high"])
            side = "above 0" if lo > 0 else "below 0" if hi < 0 else "includes 0"
            out.append(
                f"| {r['rater']} | {r['family']} | {r['measure']} | {_f(r['own_gap'], 2)} | "
                f"{_f(r['baseline_gap'], 2)} | {_f(r['self_preference'], 2)} {_ci(lo, hi, 2)} | {side} |"
            )
        out.append("")

    replaced = _by(_read(res / "own-vendor-replaced" / "variance_table.csv"), "dimension")
    if replaced:
        rt = replaced["total"]
        out += [
            "Exploratory, not pre-registered: H4 with each LLM rater's own-vendor scores replaced by the mean "
            "of the other raters (`results/own-vendor-replaced/`).",
            "",
            f"- delta omega squared: {_f(rt['delta_omega2'])}, 95% CI {_ci(rt['ci_low'], rt['ci_high'])}",
            f"- omega squared, mode: {_f(rt['omega2_mode'])}. Family: {_f(rt['omega2_family'])}",
            f"- reasoning minus fast: {_effect(rt)}",
            f"- verdict: {rt['verdict']} (consensus {t['verdict'] if t else 'not run'})",
            "",
        ]

    return "\n".join(out).rstrip() + "\n"


def write_report(results: str | Path = "results", scores: str | Path = "data/scores", out: str | Path = "") -> Path:
    path = Path(out) if out else Path(results) / "report.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_report(results, scores), encoding="utf-8")
    return path
